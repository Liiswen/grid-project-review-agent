def render(stage):
    points = read_points(stage)
    lines = [
        "国家电网有限公司电网数字化项目检查细则",
        "来源：附件2.电网数字化项目检查要点.xlsx及D:\\桌面\\实习\\规章制度相关制度文件",
        f"阶段：{stage}",
        "说明：本文件完整保留附件2开发实施项目检查表对应阶段的检查要点，并结合规章制度补充操作指导。",
        "",
    ]
    for i, point in enumerate(points, 1):
        basis = point["basis"].replace("\n", "；")
        lines.extend([
            f"【检查项{i}】{point['title']}",
            f"【对应文件】{point['documents']}",
            f"【依据】{basis}",
            "操作指导：",
            f"原始检查要求：{point['title']}",
            detail(stage, point["title"]),
            "判定边界：已取得并能核对的材料明确符合要求时判定为“合格”；材料内容明确违反要求时判定为“不合格”；文件未提供、文件虽存在但关键页未展示、系统记录或签章无法核验时判定为“无法判断”，并提出具体人工核验事项，不得仅因文件名不一致判定缺失。",
            "",
        ])
    return "\n".join(lines).rstrip() + "\n"


def main():
    OUTPUT.mkdir(exist_ok=True)
    for stage in STAGES:
        (OUTPUT / f"{stage}.txt").write_text(render(stage), encoding="utf-8")
        print(stage, len(read_points(stage)))


if __name__ == "__main__":
    main()
