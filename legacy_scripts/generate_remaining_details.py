def read_points(stage):
    text = (POINTS / f"{stage}.txt").read_text(encoding="utf-8")
    pattern = re.compile(
        r"【检查项(?P<seq>\d+)】(?P<title>[^\n]+)\n"
        r".*?【对应文件】(?P<documents>[^\n]+)\n"
        r".*?【依据】(?P<basis>[^\n]+)", re.S,
    )
    return [
        {
            "seq": int(m.group("seq")),
            "title": m.group("title").strip(),
            "documents": m.group("documents").strip(),
            "basis": m.group("basis").strip(),
        }
        for m in pattern.finditer(text)
    ]


